  add constraint sedes_google_count_valid check (google_reviews_count is null or google_reviews_count >= 0);

create table if not exists public.invitaciones_resena (
 id bigint generated by default as identity primary key,
 sede_id bigint not null references public.sedes(id),
 token_hash text not null unique,
 nombre_huesped text not null,
 fecha_salida date not null,
 creado_por uuid not null references auth.users(id),
 creado_en timestamptz not null default now(),
 expira_en timestamptz not null,
 usado_en timestamptz,
 constraint invitaciones_hash_valido check (token_hash ~ '^[a-f0-9]{64}$'),
 constraint invitaciones_nombre_valido check (char_length(nombre_huesped) between 2 and 120),
 constraint invitaciones_expiracion_valida check (expira_en > creado_en)
);

create table if not exists public.resenas_huespedes (
 id bigint generated by default as identity primary key,
 sede_id bigint not null references public.sedes(id),
 invitacion_id bigint not null unique references public.invitaciones_resena(id),
 nombre text not null,
 puntuacion smallint not null check (puntuacion between 1 and 5),
 comentario text not null check (char_length(comentario) between 15 and 1200),
 estado text not null default 'pendiente' check (estado in ('pendiente','publicada','rechazada')),
 creado_en timestamptz not null default now(),
 revisado_en timestamptz,
 revisado_por uuid references auth.users(id)
);

create index if not exists resenas_huespedes_sede_estado on public.resenas_huespedes(sede_id,estado,creado_en desc);
create index if not exists invitaciones_sede on public.invitaciones_resena(sede_id,creado_en desc);
grant select,insert on public.invitaciones_resena to authenticated;
grant select on public.resenas_huespedes to authenticated,anon;
grant usage on sequence public.invitaciones_resena_id_seq to authenticated;

create or replace function public.puede_administrar_sede(p_sede bigint)
returns boolean language sql stable security definer set search_path=public
as $$
 select exists (
  select 1 from public.perfiles_admin p where p.id=auth.uid() and p.activo
  and (p.rol='general' or (p.rol='sede' and exists (
   select 1 from public.admin_sedes a where a.admin_id=p.id and a.sede_id=p_sede
  )))
 );
$$;
revoke all on function public.puede_administrar_sede(bigint) from public;
grant execute on function public.puede_administrar_sede(bigint) to authenticated;

alter table public.invitaciones_resena enable row level security;
alter table public.resenas_huespedes enable row level security;

drop policy if exists invitaciones_admin_select on public.invitaciones_resena;
create policy invitaciones_admin_select on public.invitaciones_resena
 for select to authenticated using (public.puede_administrar_sede(sede_id));
drop policy if exists invitaciones_admin_insert on public.invitaciones_resena;
create policy invitaciones_admin_insert on public.invitaciones_resena
 for insert to authenticated with check (public.puede_administrar_sede(sede_id) and creado_por=auth.uid());

drop policy if exists resenas_admin_select on public.resenas_huespedes;
create policy resenas_admin_select on public.resenas_huespedes
 for select to authenticated using (public.puede_administrar_sede(sede_id));
drop policy if exists resenas_public_select on public.resenas_huespedes;
create policy resenas_public_select on public.resenas_huespedes
 for select to anon using (estado='publicada' and exists (
  select 1 from public.sedes s where s.id=sede_id and s.publicado
 ));
drop policy if exists resenas_admin_update on public.resenas_huespedes;
create policy resenas_admin_update on public.resenas_huespedes
 for update to authenticated using (public.puede_administrar_sede(sede_id))
 with check (public.puede_administrar_sede(sede_id));
-- El personal puede cambiar el estado, nunca la puntuación ni el comentario.
revoke update on public.resenas_huespedes from anon,authenticated;
grant update (estado,revisado_en,revisado_por) on public.resenas_huespedes to authenticated;

-- La consulta pública nunca expone el hash ni los datos internos de la invitación.
create or replace function public.consultar_invitacion_resena(p_hash text)
returns table(nombre_huesped text, nombre_sede text, estado text)
language sql security definer set search_path=public
as $$
 select i.nombre_huesped,s.nombre,
 case when i.usado_en is not null then 'usado'
      when i.expira_en<=now() then 'vencido'
      when not s.publicado then 'no_disponible'
      else 'valido' end
 from public.invitaciones_resena i
 join public.sedes s on s.id=i.sede_id
 where i.token_hash=p_hash and char_length(p_hash)=64;
$$;
revoke all on function public.consultar_invitacion_resena(text) from public;
grant execute on function public.consultar_invitacion_resena(text) to anon,authenticated;

-- Operación atómica: una invitación admite una sola reseña.
create or replace function public.enviar_resena_verificada(p_hash text,p_puntuacion integer,p_comentario text)
returns boolean language plpgsql security definer set search_path=public
as $$
declare invitacion record;
begin
 if p_puntuacion not between 1 and 5
 or char_length(btrim(p_comentario)) not between 15 and 1200
 or char_length(p_hash)<>64 then return false; end if;
 update public.invitaciones_resena i
 set usado_en=now()
 where i.token_hash=p_hash and i.usado_en is null and i.expira_en>now()
 and exists(select 1 from public.sedes s where s.id=i.sede_id and s.publicado)
 returning i.id,i.sede_id,i.nombre_huesped into invitacion;
 if not found then return false; end if;
 insert into public.resenas_huespedes(sede_id,invitacion_id,nombre,puntuacion,comentario)
 values(invitacion.sede_id,invitacion.id,invitacion.nombre_huesped,p_puntuacion,btrim(p_comentario));
 return true;
end;
$$;
revoke all on function public.enviar_resena_verificada(text,integer,text) from public;
grant execute on function public.enviar_resena_verificada(text,integer,text) to anon,authenticated;
