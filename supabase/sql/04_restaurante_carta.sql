-- Hotel Los Faroles · Carta gastronómica por restaurante
-- Ejecutar en Supabase > SQL Editor. No modifica datos existentes.
create table if not exists public.restaurante_platillos (
 id bigint generated by default as identity primary key,
 sede_id bigint not null references public.sedes(id) on delete cascade,
 categoria varchar(80) not null,
 nombre varchar(150) not null,
 descripcion varchar(500),
 precio numeric(10,2),
 imagen_url text,
 publicado boolean not null default false,
 orden integer not null default 0,
 creado_en timestamptz not null default now(),
 actualizado_en timestamptz not null default now(),
 constraint restaurante_platillos_nombre_check check (length(trim(nombre)) >= 2),
 constraint restaurante_platillos_precio_check check (precio is null or precio >= 0)
);
create index if not exists restaurante_platillos_sede_orden_idx on public.restaurante_platillos(sede_id, orden, id);
alter table public.restaurante_platillos enable row level security;

-- Los visitantes solo ven platos publicados de restaurantes publicados.
drop policy if exists "restaurante_carta_publica" on public.restaurante_platillos;
create policy "restaurante_carta_publica" on public.restaurante_platillos
for select to anon, authenticated using (
 publicado and exists (
  select 1 from public.sedes s where s.id = sede_id and s.tipo = 'restaurante' and s.publicado
 )
);

-- El administrador general o asignado a la sede puede administrar su carta.
drop policy if exists "restaurante_carta_admin_select" on public.restaurante_platillos;
create policy "restaurante_carta_admin_select" on public.restaurante_platillos
for select to authenticated using (
 exists(select 1 from public.sedes s join public.perfiles_admin p on p.id = (select auth.uid())
 where s.id = sede_id and s.tipo = 'restaurante' and p.activo
 and (p.rol = 'general' or (p.rol = 'sede' and exists(
 select 1 from public.admin_sedes a where a.admin_id = p.id and a.sede_id = s.id))))
);
